package pl.ignix.launcher.ui;

import java.awt.Color;
import java.awt.Graphics2D;
import java.util.HashMap;
import java.util.Map;

/** Hand-drawn 5x7 pixel font for headings (A-Z, 0-9 and a few signs). Lowercase is drawn as uppercase. */
final class PixelFont {

    private static final Map<Character, String[]> GLYPHS = new HashMap<>();

    private static void g(char c, String... rows) {
        GLYPHS.put(c, rows);
    }

    static {
        g('A', ".###.", "#...#", "#...#", "#####", "#...#", "#...#", "#...#");
        g('B', "####.", "#...#", "#...#", "####.", "#...#", "#...#", "####.");
        g('C', ".####", "#....", "#....", "#....", "#....", "#....", ".####");
        g('D', "####.", "#...#", "#...#", "#...#", "#...#", "#...#", "####.");
        g('E', "#####", "#....", "#....", "####.", "#....", "#....", "#####");
        g('F', "#####", "#....", "#....", "####.", "#....", "#....", "#....");
        g('G', ".####", "#....", "#....", "#.###", "#...#", "#...#", ".###.");
        g('H', "#...#", "#...#", "#...#", "#####", "#...#", "#...#", "#...#");
        g('I', "#####", "..#..", "..#..", "..#..", "..#..", "..#..", "#####");
        g('J', "..###", "...#.", "...#.", "...#.", "#..#.", "#..#.", ".##..");
        g('K', "#...#", "#..#.", "#.#..", "##...", "#.#..", "#..#.", "#...#");
        g('L', "#....", "#....", "#....", "#....", "#....", "#....", "#####");
        g('M', "#...#", "##.##", "#.#.#", "#.#.#", "#...#", "#...#", "#...#");
        g('N', "#...#", "##..#", "#.#.#", "#..##", "#...#", "#...#", "#...#");
        g('O', ".###.", "#...#", "#...#", "#...#", "#...#", "#...#", ".###.");
        g('P', "####.", "#...#", "#...#", "####.", "#....", "#....", "#....");
        g('Q', ".###.", "#...#", "#...#", "#...#", "#.#.#", "#..#.", ".##.#");
        g('R', "####.", "#...#", "#...#", "####.", "#.#..", "#..#.", "#...#");
        g('S', ".####", "#....", "#....", ".###.", "....#", "....#", "####.");
        g('T', "#####", "..#..", "..#..", "..#..", "..#..", "..#..", "..#..");
        g('U', "#...#", "#...#", "#...#", "#...#", "#...#", "#...#", ".###.");
        g('V', "#...#", "#...#", "#...#", "#...#", "#...#", ".#.#.", "..#..");
        g('W', "#...#", "#...#", "#...#", "#.#.#", "#.#.#", "##.##", "#...#");
        g('X', "#...#", "#...#", ".#.#.", "..#..", ".#.#.", "#...#", "#...#");
        g('Y', "#...#", "#...#", ".#.#.", "..#..", "..#..", "..#..", "..#..");
        g('Z', "#####", "....#", "...#.", "..#..", ".#...", "#....", "#####");
        g('0', ".###.", "#...#", "#..##", "#.#.#", "##..#", "#...#", ".###.");
        g('1', "..#..", ".##..", "..#..", "..#..", "..#..", "..#..", ".###.");
        g('2', ".###.", "#...#", "....#", "...#.", "..#..", ".#...", "#####");
        g('3', "####.", "....#", "....#", ".###.", "....#", "....#", "####.");
        g('4', "#..#.", "#..#.", "#..#.", "#####", "...#.", "...#.", "...#.");
        g('5', "#####", "#....", "####.", "....#", "....#", "#...#", ".###.");
        g('6', ".###.", "#....", "#....", "####.", "#...#", "#...#", ".###.");
        g('7', "#####", "....#", "...#.", "..#..", ".#...", ".#...", ".#...");
        g('8', ".###.", "#...#", "#...#", ".###.", "#...#", "#...#", ".###.");
        g('9', ".###.", "#...#", "#...#", ".####", "....#", "....#", ".###.");
        g('.', ".....", ".....", ".....", ".....", ".....", ".....", "..#..");
        g('-', ".....", ".....", ".....", ".###.", ".....", ".....", ".....");
        g('!', "..#..", "..#..", "..#..", "..#..", "..#..", ".....", "..#..");
        g(':', ".....", "..#..", ".....", ".....", ".....", "..#..", ".....");
        g('/', "....#", "....#", "...#.", "..#..", ".#...", "#....", "#....");
        g('\'', "..#..", "..#..", ".....", ".....", ".....", ".....", ".....");
        g('?', ".###.", "#...#", "....#", "...#.", "..#..", ".....", "..#..");
    }

    private PixelFont() {
    }

    static int width(String s, int scale) {
        return s.isEmpty() ? 0 : (s.length() * 6 - 1) * scale;
    }

    static int height(int scale) {
        return 7 * scale;
    }

    /** Draws text with a 1-pixel drop shadow (like Minecraft). */
    static void draw(Graphics2D g, String s, int x, int y, int scale, Color color, boolean shadow) {
        if (shadow) {
            Color sc = new Color(color.getRed() / 4, color.getGreen() / 4, color.getBlue() / 4, color.getAlpha());
            drawRaw(g, s, x + scale, y + scale, scale, sc);
        }
        drawRaw(g, s, x, y, scale, color);
    }

    private static void drawRaw(Graphics2D g, String s, int x, int y, int scale, Color color) {
        g.setColor(color);
        int cx = x;
        for (char ch : s.toUpperCase().toCharArray()) {
            String[] rows = GLYPHS.get(ch);
            if (rows != null) {
                for (int r = 0; r < 7; r++) {
                    for (int c = 0; c < 5; c++) {
                        if (rows[r].charAt(c) == '#') {
                            g.fillRect(cx + c * scale, y + r * scale, scale, scale);
                        }
                    }
                }
            }
            cx += 6 * scale;
        }
    }
}
